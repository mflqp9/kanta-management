-- 1) پارٹیاں / کسان
--    gaon: ایپ میں «موضع» کے نام سے
--    zamanat: ضمانتی کاغذات — ادائیگی / ایڈوانس کے بدلے لیے گئے چیک، اسٹامپ پیپر وغیرہ کی تفصیل
--    nisbat: walid_ka_naam کس کا نام ہے — 'walid' (والد: «اکرم ولد رسول») یا
--            'reference' (ریفرینس: جب نام کسی فرم / کاروبار کا ہو اور ساتھ حوالہ دینے والے کا نام)
--    khata_number: کھاتہ نمبر — خودکار ترتیب وار نمبر (1، 2، 3 …)، ہر پارٹی کا الگ؛ حذف شدہ نمبر دوبارہ نہیں ملتا
--    mobile_number_2: دوسرا موبائل نمبر — اختیاری (خالی ہو تو null)
-- ---------------------------------------------------------------------
create table if not exists public.parties (
  id             uuid primary key default gen_random_uuid(),
  khata_number   bigint generated by default as identity unique,
  naam           text not null,
  walid_ka_naam  text,
  nisbat         text not null default 'walid' constraint parties_nisbat_check check (nisbat in ('walid', 'reference')),
  mobile_number  text,
  mobile_number_2 text,
  gaon           text,
  qism           text default 'کسان',
  zamanat        text,
  created_at     timestamptz not null default now()
);

-- پرانا ڈیٹا بیس: ضمانتی کاغذات اور والد / ریفرینس کے کالم شامل کریں — پہلے سے ہوں تو کچھ نہیں ہوتا
-- (پرانی پارٹیوں پر nisbat خود 'walid' لگ جاتا ہے؛ کوئی ریکارڈ حذف نہیں ہوتا)
alter table public.parties add column if not exists zamanat text;
alter table public.parties add column if not exists mobile_number_2 text;
alter table public.parties
  add column if not exists nisbat text not null default 'walid'
    constraint parties_nisbat_check check (nisbat in ('walid', 'reference'));

-- پرانا ڈیٹا بیس: کھاتہ نمبر — موجودہ پارٹیوں کو بننے کی ترتیب (created_at) سے 1، 2، 3 … نمبر،
-- پھر نئی پارٹی کو اگلا نمبر خود ملتا ہے۔ کالم پہلے سے ہو تو کچھ نہیں ہوتا؛ کوئی ریکارڈ حذف نہیں ہوتا
do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'parties' and column_name = 'khata_number'
  ) then
    alter table public.parties add column khata_number bigint;
    update public.parties p
       set khata_number = n.rn
      from (select id, row_number() over (order by created_at, id) as rn from public.parties) n
     where n.id = p.id;
    alter table public.parties alter column khata_number set not null;
    alter table public.parties alter column khata_number add generated by default as identity;
    perform setval(
      pg_get_serial_sequence('public.parties', 'khata_number'),
      coalesce((select max(khata_number) from public.parties), 0) + 1,
      false
    );
    alter table public.parties add constraint parties_khata_number_key unique (khata_number);
  end if;
end;
$$;


